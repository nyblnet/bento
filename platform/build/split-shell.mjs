// Splits a built bento/slides shell into the two halves either side of the
// #bento-doc block, so the platform Worker can serve a stored deck as
// `SHELL_HEAD + escape(JSON.stringify(doc)) + SHELL_TAIL` — string
// concatenation, no HTML parsing, no per-request regex scan of a ~700KB
// shell. This is the same split kernel/src/save.ts's serializeBody() does at
// SAVE time in a live DOM (clone → swap block → outerHTML); here it happens
// once at BUILD time against the static release artifact, because a Worker
// has no DOM to clone.
//
// The regex and the escape rule are copied from scripts/shell-gate.mjs
// (DOC_BLOCK_RE / escapeBlockText) rather than imported, matching that file's
// own reasoning: a generator sharing code with the thing that gates it cannot
// notice the two drifting apart. platform/worker/test/splice.test.mjs re-runs
// the shell-gate invariants against the SPLICED output to keep both honest.
//
// Usage:
//   node platform/build/split-shell.mjs <path-to-shell.html> [--out <file>]
//
// Default input: slides/dist-single/Bento_Slides.bento.html (build it first
// with `npm run build:single` inside slides/). Default output:
// platform/worker/src/generated/shell.ts (gitignored — regenerate, don't
// hand-edit, and don't commit it).

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = dirname(dirname(here))

const DOC_BLOCK_OPEN = '<script type="application/bento+json" id="bento-doc">'
const SCRIPT_CLOSE = '</scr' + 'ipt>'
const DOC_BLOCK_RE = /<script type="application\/bento\+json" id="bento-doc">[\s\S]*?<\/script>/

const die = (msg) => {
  console.error(`✗ ${msg}`)
  process.exit(1)
}

const args = process.argv.slice(2)
const outFlagIdx = args.indexOf('--out')
const outPath = outFlagIdx >= 0 ? args[outFlagIdx + 1] : null
const inputArg = args.find((a, i) => !a.startsWith('--') && args[i - 1] !== '--out')

const shellPath = resolve(inputArg ?? join(repoRoot, 'slides/dist-single/Bento_Slides.bento.html'))
if (!existsSync(shellPath)) {
  die(`no shell at ${shellPath} — run \`npm run build:single\` in slides/ first`)
}

const shell = readFileSync(shellPath, 'utf8')
const match = shell.match(DOC_BLOCK_RE)
if (!match) die(`#bento-doc block not found in ${shellPath} — is this a built bento/slides shell?`)

const matchStart = match.index
const matchEnd = matchStart + match[0].length

// HEAD ends right after the opening tag + a newline (matches serializeBody's
// `DOC_BLOCK_OPEN + '\n' + escaped + '\n' + SCRIPT_CLOSE` layout exactly, so
// splicing here is byte-identical in shape to what a real save produces).
const head = shell.slice(0, matchStart) + DOC_BLOCK_OPEN + '\n'
const tail = '\n' + SCRIPT_CLOSE + shell.slice(matchEnd)

// Sanity: HEAD + <anything> + TAIL must reconstruct a shell with exactly one
// script-tag count higher than an empty splice — i.e. the halves really do
// bracket one script element and nothing else was lost or duplicated.
const roundTrip = head + '' + tail
const opensOrig = (shell.match(/<script[\s>]/g) ?? []).length
const opensRT = (roundTrip.match(/<script[\s>]/g) ?? []).length
if (opensOrig !== opensRT) die(`script-tag count changed by the split (${opensOrig} → ${opensRT}) — refusing to generate`)

let pkgVersion = '0.0.0'
try {
  pkgVersion = JSON.parse(readFileSync(join(repoRoot, 'slides/package.json'), 'utf8')).version
} catch {
  // fall through with the placeholder — non-fatal, this is a label only
}

const shellHash = createHash('sha256').update(shell).digest('hex').slice(0, 16)

const generated = `// AUTO-GENERATED by platform/build/split-shell.mjs — do not edit by hand.
// Source shell: ${shellPath.replace(repoRoot, '').replace(/\\/g, '/')}
// Regenerate after every slides build with a shell you intend to serve.

/** slides/package.json version at split time — a display label, not a contract. */
export const SHELL_VERSION = ${JSON.stringify(pkgVersion)}

/** First 16 hex chars of sha256(shell) at split time — cache-busting / debugging only. */
export const SHELL_HASH = ${JSON.stringify(shellHash)}

/** Everything up to and including the #bento-doc block's opening tag + newline. */
export const SHELL_HEAD = ${JSON.stringify(head)}

/** A newline, the block's closing tag, and everything after it. */
export const SHELL_TAIL = ${JSON.stringify(tail)}
`

const dest = resolve(outPath ?? join(here, '..', 'worker', 'src', 'generated', 'shell.ts'))
mkdirSync(dirname(dest), { recursive: true })
writeFileSync(dest, generated)
console.log(`✓ split shell (${shell.length} bytes) → ${dest.replace(repoRoot, '').replace(/\\/g, '/')}`)
console.log(`  version ${pkgVersion}, hash ${shellHash}, head ${head.length}B, tail ${tail.length}B`)
