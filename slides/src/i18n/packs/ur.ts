// what Urdu speakers see in Office (سلائیڈ, پریزنٹیشن, خاکہ, جدول, فونٹ,
// چارٹ). t() has no plural machinery; Urdu leaves the noun unmarked after a
// numeral, so counted strings are phrased count-agnostically and read
