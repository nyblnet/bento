// Urdu is right-to-left, the third RTL language here after Hebrew and
// Persian, and it lands in a shell that already mirrors its chrome.
// Orthography is URDU, not Arabic and not Persian: the Urdu letters
// ٹ ڈ ڑ ں ے ہ ھ are used where they belong, ی is U+06CC and ک is U+06A9 —
// never the Arabic ي/ك — and ہ (U+06C1) / ے (U+06D2) appear where Urdu
// spelling requires them. ZWNJ (U+200C) is a joiner and is permitted here —
// it is NOT a bidi control — but unlike Persian, which needs it constantly
// (می‌شود, به‌روزرسانی), Urdu writes the same compounds with a plain space
// (غیر محفوظ, ہم آہنگ, خود مختار) or an izafat kasra (اشتراکِ کار), so this
// catalog uses none. Zero ZWNJ is the correct Urdu answer, not an omission.
// There are NO bidi control characters in this file either: strings mixing
// Urdu with a Latin token, a shortcut or a number are REPHRASED so the
// punctuation lands right, never steered with marks.
// Digits stay Western (0-9) — page and slide numbers are document content
// and must read identically for every viewer.
//
// Directional arrows are MIRRORED. U+2192 → is not Bidi_Mirrored, so a key
// that ends in → is answered with ← (U+2190) in the value; the "Save →
// Version history" breadcrumb flips for the same reason. The keys keep their
// → untouched — they are the English source strings.
//
// Nastaliq is typographically demanding and Urdu sets long, so panel labels
// and tooltips are kept deliberately short; a few sentences are condensed
// rather than translated clause for clause.
//
