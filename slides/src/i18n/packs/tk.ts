// Terminology follows the Latin-script conventions Turkmen speakers meet in
// localized office software (slaýd, prezentasiýa, ýerleşiş, element, geçiş,
// doldurma, kontur, şrift). One rendering per concept, never varied.
//
// Four Turkmen-specific rules held throughout:
//   * The KEY is the English source string and must match it byte for byte —
//     curly apostrophes (’), em dashes (—), ⌘ and → included. A mistyped key
//     is silently dead: it falls back to English with no error.
//   * No plural machinery exists in t(), and Turkmen needs none — a noun after
//     a numeral stays singular ("3 slaýd", never "3 slaýdlar").
//   * Suffixes harmonise with the preceding vowel, so a suffix glued to an
//     interpolated {placeholder} would be wrong for half the values it ever
//     sees. Those strings are rephrased — the value goes after a colon, the
//     suffix lands on a following word ("{n} belgili slaýd"), or the sentence
//     is built so no case suffix is needed ("Täzelendi: v{v}.").
//   * Homonyms the English source keeps apart are kept apart here too:
//     Outline/Interior (the text-stroke pair) are "daş çyzyk"/"iç doldurma"
//     while Stroke is "kontur"; Checking… is "Barlanýar…" and Verifying… is
//     "Tassyklanýar…"; Cancel is "Ýatyr" and Discard is "Taşla"; Chart is
//     "diagramma" and Diagram is "shema". The source split Loop in two on
//     purpose — 'Loop' is the media toggle ("Gaýtala"), 'Loop animation' is
//     the fx row ("Animasiýa aýlawy"); do not collapse them.
//
// Two word choices that look wrong and are not:
//   * Opacity is "görnüklilik", NOT "durulyk" — "dury" means transparent, so
//     "durulyk" names the inverse of the value the field holds.
//   * Save is "saklamak", not "ýatda saklamak" (= to memorise).
