//
// REGISTER: natural Taglish, deliberately. English is an official language of
// the Philippines and everyday Filipino tech speech is heavily code-switched;
// purist coinages (Komisyon sa Wikang Filipino terminology, "panlaping"
// constructions) read as stilted or unintelligible to the people who actually
// use this software. So English technical nouns are KEPT — slide, deck, file,
// browser, layout, chart, series, axis, fill, stroke, opacity, morph, state,
// live session, password — and the Filipino carries the grammar, the verbs and
// the connective tissue around them. Where a Filipino word is genuinely the
// everyday one it is used: kulay, laki, lapad, taas, hugis, linya, larawan,
// teksto, pamagat, may-ari, bisita, wika, komento.
//
// VERBS: one convention throughout — the i-/-in/-an imperative. Loan verbs
// take i- (I-save, I-download, I-undo, I-duplicate, I-apply, I-export);
// native verbs keep their own imperative (Burahin, Tanggalin, Buksan, Piliin,
// Ibahagi, Simulan, Ihinto). Second person is informal singular (mo/ka/iyon)
// to match the English source's direct address; no "po".
//
// PLURALS: Filipino has no grammatical plural agreement — plurality is marked
// with the particle "mga", and UI text often omits it. Counted strings are
// written to read correctly for any n; a numeral is never followed by "mga"
// (Filipino does not double-mark), so "{n} slide", not "{n} mga slide".
//
// Machine-drafted and NOT reviewed by a native speaker.
