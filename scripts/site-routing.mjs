// Host routing files for bento.page on Cloudflare Workers static assets.
//
// The site is a plain tree of files, and GitHub Pages serves it with a few
// conveniences every published URL now depends on: `/x.html` AND `/x` both
// answer 200, `/d/` serves `d/index.html`, and `/d` redirects to `/d/`.
// Workers static assets offers those only bundled with a canonicalisation we
// cannot have: its default `html_handling` answers `/x.html` with a redirect
// to `/x`, and that would move the signed shell URL inside every shipped
// manifest (`/releases/slides/Bento_Slides.bento.html`). So the site runs with
// `html_handling = "none"` (only exact file paths match) and this module
// generates the `_redirects` that put the other forms back, one rule per HTML
// file in the tree being published. Generated, never hand-written: a gallery
// deck added later would otherwise 404 at its extensionless URL.
//
// It also generates the tail of `_headers`. The hand-written head
// (site-src/host/_headers) sets `Content-Type: text/html; charset=utf-8` on
// /*, because GitHub Pages sent the charset and production Workers does not,
// and only a /* rule reaches every 404. Each file that is not HTML then needs
// its own rule that deletes that value and sets the right one, and each
// directory 301 needs its type deleted. A header two rules both SET is joined
// with a comma, so no rule here ever sets Content-Type without deleting first.
//
// `wrangler.toml` and `.assetsignore` live in site-src/host/ and are copied
// as they are.
// publish-site.mjs calls stageHostFiles() on the tree it is about to mirror.
// GitHub Pages serves all four as inert text until the move; Workers reads
// them and serves none of them.

import { copyFileSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/** Files this module writes into the site root. */
export const HOST_FILES = ['_headers', '_redirects', 'wrangler.toml', '.assetsignore']

function walk(dir, base = dir) {
  const out = []
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name === '.git') continue
    const full = join(dir, e.name)
    if (e.isDirectory()) out.push(...walk(full, base))
    else out.push(full.slice(base.length + 1).split('\\').join('/'))
  }
  return out
}

/**
 * `_redirects` for `html_handling = "none"`, from the tree's relative paths.
 *   index.html        →  `/ /index.html 200`
 *   d/index.html      →  `/d/ /d/index.html 200` and `/d /d/ 301`
 *   x.html            →  `/x /x.html 200`   (the extensionless form)
 * A 200 rule is a rewrite: the asset at the target is served at the source
 * URL. `/x.html` itself needs no rule, it is an exact file match.
 */
export function workersRedirects(files) {
  const html = files.filter((f) => f.endsWith('.html') && !HOST_FILES.includes(f)).sort()
  const lines = []
  for (const f of html) {
    if (f === 'index.html') lines.push('/ /index.html 200')
    else if (f.endsWith('/index.html')) {
      const d = '/' + f.slice(0, -'index.html'.length)
      lines.push(`${d} /${f} 200`, `${d.slice(0, -1)} ${d} 301`)
    } else lines.push(`/${f.slice(0, -'.html'.length)} /${f} 200`)
  }
  // Workers allows 2,000 static rules; fail loudly long before a silent cut-off.
  if (lines.length > 1900) throw new Error(`_redirects would have ${lines.length} rules; Workers allows 2,000`)
  return lines.join('\n') + '\n'
}

/**
 * Content-Type for every kind of file the site serves that is not HTML, by
 * extension ('' = none: LICENSE, CNAME, .nojekyll). What GitHub Pages sent.
 * A file of any other kind stops the publish: it would otherwise be served
 * as text/html by the /* rule.
 */
export const CONTENT_TYPES = {
  md: 'text/markdown; charset=utf-8',
  txt: 'text/plain; charset=utf-8',
  json: 'application/json; charset=utf-8',
  xml: 'application/xml',
  png: 'image/png',
  zip: 'application/x-zip-compressed',
  '': 'application/octet-stream',
}

/** Marks where the generated part of `_headers` begins. */
export const HEADERS_MARKER = '# ---- generated by scripts/site-routing.mjs; do not edit below ----'

function extensionOf(f) {
  const base = f.slice(f.lastIndexOf('/') + 1)
  const dot = base.lastIndexOf('.')
  return dot > 0 ? base.slice(dot + 1) : ''
}

/**
 * The generated tail of `_headers`, from the tree's relative paths.
 *   x.html                    →  nothing (the head's /* rule is right)
 *   d/index.html              →  `/d` deletes Content-Type (its 301 has no body)
 *   other files               →  `/f` deletes Content-Type, sets its own
 *   dir/ of ≥ 2 files, all one non-HTML type, nothing else  →  one `/dir/:file`
 * The directory rule keeps the rule count flat as releases add schema files
 * and language packs (Workers allows 100 rules). Its cost: a MISSING file in
 * that directory 404s with that type on an HTML body. No other 404 is touched.
 */
export function workersHeaders(files) {
  const served = files.filter((f) => !HOST_FILES.includes(f)).sort()
  const typeOf = (f) => {
    if (f.endsWith('.html')) return null
    const t = CONTENT_TYPES[extensionOf(f)]
    if (!t) throw new Error(`site-routing: no Content-Type for ${f}; add its extension to CONTENT_TYPES`)
    return t
  }
  const byDir = new Map()
  for (const f of served) {
    const d = f.includes('/') ? f.slice(0, f.lastIndexOf('/')) : ''
    if (!byDir.has(d)) byDir.set(d, [])
    byDir.get(d).push(f)
  }
  const rules = []
  const rule = (path, type) => rules.push(type ? `${path}\n  ! Content-Type\n  Content-Type: ${type}` : `${path}\n  ! Content-Type`)
  for (const [d, list] of [...byDir].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    const types = new Set(list.map(typeOf))
    if (d && list.length >= 2 && types.size === 1 && !types.has(null)) {
      rule(`/${d}/:file`, list.map(typeOf)[0])
      continue
    }
    for (const f of list) {
      const t = typeOf(f)
      if (t) rule(`/${f}`, t)
      else if (f.endsWith('/index.html')) rule(`/${f.slice(0, -'/index.html'.length)}`)
    }
  }
  // Workers allows 100 header rules, the head uses 1; fail loudly, never cut off.
  if (rules.length > 90) throw new Error(`_headers would have ${rules.length + 1} rules; Workers allows 100`)
  return HEADERS_MARKER + '\n' + rules.join('\n') + '\n'
}

/** Write the host files into `site` (the tree publish-site.mjs mirrors). */
export function stageHostFiles(site, root) {
  for (const f of ['wrangler.toml', '.assetsignore']) {
    copyFileSync(join(root, 'site-src/host', f), join(site, f))
  }
  const files = walk(site)
  const head = readFileSync(join(root, 'site-src/host/_headers'), 'utf8')
  writeFileSync(join(site, '_headers'), head.trimEnd() + '\n\n' + workersHeaders(files))
  writeFileSync(join(site, '_redirects'), workersRedirects(files))
}
